#include <iostream>
#include <vector>
using namespace std;
int main(){
  vector <int> a(10,2021);
  int until;
  for(int i =1;[](vector<int> &a){
    for(auto g:a){
      if(g<0){
        return false;
      }
    }
    return true;
  }(a);++i){
    int x = i;
    for(;x;x/=10){
      int w=x%10;
      a[w]--;
    }
    until = i;
  }
  cout << until;
}
